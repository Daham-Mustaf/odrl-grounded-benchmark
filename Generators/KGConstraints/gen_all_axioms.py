"""
gen_all_axioms.py
=================
Convenience runner that generates all theory axiom files for the
ODRL KGConstraints benchmark.  Knowledge files (GeoNames, DPV, BCP 47)
are generated by gen_all_resources.py.

Output (theory):
    Problems/ODRL/KGConstraints/Axioms/KGE000-0.ax
    Problems/ODRL/KGConstraints/Axioms/DENOT000-0.ax
    Problems/ODRL/KGConstraints/Axioms/COMPOSE000-0.ax
    Problems/ODRL/KGConstraints/Axioms/REFINE000-0.ax
    Problems/ODRL/KGConstraints/Axioms/MONO000-0.ax
    Problems/ODRL/KGConstraints/Axioms/ALIGN000-0.ax
    Problems/ODRL/KGConstraints/Axioms/RUNTIME000-0.ax

Usage:
    uv run Generators/KGConstraints/gen_all_axioms.py
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from gen_primitives    import generate_kge000,     EXPECTED_COUNT as N_KGE
from gen_denotation    import generate_denot000,   EXPECTED_COUNT as N_DENOT
from gen_composition   import generate_compose000, EXPECTED_COUNT as N_COMP
from gen_monotonicity  import generate_mono000,    EXPECTED_COUNT as N_MONO
from gen_alignment     import generate_align000,   EXPECTED_COUNT as N_ALIGN
from gen_runtime       import generate_runtime000, EXPECTED_COUNT as N_RT

FILES = [
    ("KGE000-0.ax",     generate_kge000,     N_KGE),
    ("DENOT000-0.ax",   generate_denot000,   N_DENOT),
    ("COMPOSE000-0.ax", generate_compose000, N_COMP),
    ("MONO000-0.ax",    generate_mono000,    N_MONO),
    ("ALIGN000-0.ax",   generate_align000,   N_ALIGN),
    ("RUNTIME000-0.ax", generate_runtime000, N_RT),
]


def main():
    parser = argparse.ArgumentParser(
        description="Generate all theory axiom files for KGConstraints."
    )
    parser.add_argument("--out-dir",
                        default="Problems/ODRL/KGConstraints/Axioms")
    args = parser.parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    total = 0
    all_ok = True
    for name, gen, expected in FILES:
        content = gen()
        actual = content.count("fof(")
        ok = actual == expected
        total += actual
        if not ok:
            all_ok = False
        path = out_dir / name
        path.write_text(content, encoding="utf-8")
        mark = "✓" if ok else "✗"
        print(f"Written : {path}  ({actual} formulae, expected {expected}) {mark}")

    print(f"\nTotal formulae across all theory axiom files: {total}")
    print(
        "\nInclude matrix for problem files (theory + resource):\n"
        "  Conflict (Theorem 1)        : KGE000 + DENOT000 + <resource>\n"
        "  Composition (Theorem 2)     : KGE000 + DENOT000 + COMPOSE000 + <resource>\n"
        "  Refinement (Lemma 1)        : KGE000 + DENOT000 + REFINE000 + <resource>\n"
        "  Monotonicity (Prop 1)       : MONO000 + problem-local two-resource\n"
        "                                lifts of KGE000/DENOT000 + <resource_R>\n"
        "                                + <resource_R'>\n"
        "  Alignment (Prop 2 / Cor 1)  : ALIGN000 + REFINE000 (for Cor 1) +\n"
        "                                problem-local two-resource lifts of\n"
        "                                KGE000/DENOT000 + <resource_A> +\n"
        "                                <resource_B>\n"
        "  Runtime (Theorem 3)         : KGE000 + DENOT000 + RUNTIME000 +\n"
        "                                <resource>\n"
        "\n"
        "Note: Monotonicity and Alignment problems require two-resource\n"
        "lifts of KGE000 and DENOT000 (predicates suffixed _R / _R' or\n"
        "_A / _B).  These lifts are emitted by the corresponding problem-\n"
        "file generators, not by this runner."
    )
    sys.exit(0 if all_ok else 1)


if __name__ == "__main__":
    main()